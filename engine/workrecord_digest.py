"""Summarise the candidate's work from the git repos listed in workrecord.json.

    .venv/bin/python engine/workrecord_digest.py            # writes <profile>/data/workrecord_digest.txt
    .venv/bin/python engine/workrecord_digest.py --max 400  # commit subjects per repo (default 250)

For each repo: the candidate's commits (filtered by the author names/emails
listed, and by start/end dates), the folders and file types touched, and the
commit subjects. It never copies source code. An agent then turns this digest
into bank.json bullets (tasks/mine-workrecord.md), marked unverified until the
candidate confirms them. Documents and links in workrecord.json are listed for
the agent to read itself.
"""
import argparse
import collections
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import candidate  # noqa: E402


def git(repo, *args):
    r = subprocess.run(['git', '-C', repo, *args], capture_output=True, text=True)
    return r.stdout if r.returncode == 0 else ''


def digest_repo(r, max_subjects):
    path = os.path.expanduser(r['path'])
    head = f"## {r.get('project') or path}" + (f" ({r['employer']})" if r.get('employer') else '')
    lines = [head, f"path: {r['path']}"]
    if not os.path.isdir(path) or not git(path, 'rev-parse', '--git-dir'):
        return lines + ['NOT FOUND on this machine (or not a git repo): skipped.', '']
    args = ['log', '--no-merges', '--date=short', '--pretty=format:@@%ad\t%an <%ae>\t%s', '--numstat']
    for a in r.get('authors', []):
        args.append(f'--author={a}')
    if r.get('start'):
        args.append(f"--since={r['start']}-01")
    if r.get('end'):
        args.append(f"--until={r['end']}-31")
    out = git(path, *args)
    commits, dirs, exts = [], collections.Counter(), collections.Counter()
    added = removed = 0
    for line in out.splitlines():
        if line.startswith('@@'):
            date, who, subject = line[2:].split('\t', 2)
            commits.append((date, subject.strip()))
        elif line.strip():
            parts = line.split('\t')
            if len(parts) == 3:
                a, d, f = parts
                added += int(a) if a.isdigit() else 0
                removed += int(d) if d.isdigit() else 0
                top = f.split('/')[0] if '/' in f else '(root)'
                sub = '/'.join(f.split('/')[:2]) if f.count('/') >= 2 else top
                dirs[sub] += 1
                exts[os.path.splitext(f)[1].lower() or '(none)'] += 1
    if not commits:
        who = ', '.join(r.get('authors', [])) or 'anyone'
        return lines + [f'No commits by {who} in this period.', '']
    dates = sorted(d for d, _ in commits)
    lines += [f'commits: {len(commits)} ({dates[0]} to {dates[-1]}), lines +{added}/-{removed}',
              'areas touched (files changed): ' + ', '.join(f'{d} ({n})' for d, n in dirs.most_common(15)),
              'file types: ' + ', '.join(f'{e} ({n})' for e, n in exts.most_common(10)),
              f'commit subjects (newest first, up to {max_subjects}):']
    seen = set()
    for date, subject in commits:
        key = re.sub(r'\W+', ' ', subject.lower()).strip()
        if key in seen:
            continue
        seen.add(key)
        lines.append(f'  {date}  {subject}')
        if len(seen) >= max_subjects:
            break
    return lines + ['']


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--max', type=int, default=250, help='commit subjects to list per repo')
    a = ap.parse_args()
    wr = candidate.load_json('workrecord.json')
    out = ['# Work record digest', 'Generated by engine/workrecord_digest.py from workrecord.json. No source code included.', '']
    for r in wr.get('repos', []):
        out += digest_repo(r, a.max)
    for d in wr.get('documents', []):
        out.append(f"document for the agent to read: {d['path']}" + (f" ({d['about']})" if d.get('about') else ''))
    for l in wr.get('links', []):
        out.append(f"link for the agent to read: {l['url']}" + (f" ({l['about']})" if l.get('about') else ''))
    os.makedirs(candidate.path('data'), exist_ok=True)
    dest = candidate.path('data', 'workrecord_digest.txt')
    with open(dest, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print(f'wrote {os.path.relpath(dest)} ({len(out)} lines)')


if __name__ == '__main__':
    main()
